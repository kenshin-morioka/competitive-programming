// なぜp・qどちらも参照の形(&i, &j)になるのか:
// - .iter()は&selfを取るメソッドなので、呼び出し自体がベクタを借用する
//   (for x in &vec の &vec と同じ役割を .iter() が担っている)。
// - そのため p.iter() / q.iter() はどちらも Iterator<Item = &u32> を返す。
// - i + j == k は u32同士の演算が必要なので、参照のままでは型が合わない。
//   よって |&i|, |&j| というパターンでu32の値を取り出す必要がある。
// - p, qどちらも.iter()を使っている以上、扱いは完全に対称。
//
// なぜ引数は&i(参照)なのに、本体(i + j == k)には&が要らないのか:
// - |&i| は「&u32型の値をパターン&iで分解する」という分配束縛(destructuring)。
//   let &i = 参照; と同じ構造で、この時点で参照を剥がし、中身のu32をiに束縛している。
// - つまり引数リスト側で「剥がし方」を指定していて、本体ではもう剥がした後の
//   u32そのものを使っているだけ。だから&は不要。
// - 剥がすタイミングを本体側に持っていくなら |i| *i + ... のように*で剥がす書き方も可能
//   (その場合iは&u32のまま)。
