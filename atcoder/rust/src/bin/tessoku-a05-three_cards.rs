// 自分の回答
use proconio::input;

fn main() {
    input! {
        n:u32,
        k:u32,
    }
    let mut ans = 0;

    for r in 1..=n {
        for b in 1..=n {
            if r + b >= k {
                break;
            };
            if k - r - b <= n {
                ans += 1;
            }
        }
    }
    println!("{}", ans);
}

// 今回のポイント
// - 全探索の次元を 1 つ減らす: r, b を決めれば w = k - r - b は一意に決まるので、
//   三重ループ O(N^3) (N=3000 で 2.7*10^10) を二重ループ O(N^2) (9*10^6) にできる
// - 元の三重ループは最内で break していても、そこに到達するまでの二重ループは回るため
//   計算量のオーダーは落ちない (定数倍の改善にしかならない)
// - u32 の減算はアンダーフローするので、k - r - b を計算する前に r + b < k を保証する
//   (ここでは `if r + b >= k { break }` が範囲外の枝刈りと安全性の両方を兼ねている)
// - b は増加する一方なので、r + b >= k になった時点で以降も条件を満たさない → continue でなく break
